def get_instructions_for_tags(patient_tags: list[str]) -> tuple[list[str], list[str]]:
    """
    Получить списки инструкций dos и donts для заданных тегов пациента.
    
    Args:
        patient_tags: Список тегов пациента (строки из IssueType и PatientType)
    
    Returns:
        Tuple из двух списков: (dos_list, donts_list)
    """
    dos: list[str] = []
    donts: list[str] = []

    for tag in patient_tags:
        # Проверяем в issue_mapping
        try:
            tag = IssueType[tag]
            dos.append(issue_mapping[tag][InstructionType.DOS])
            donts.append(issue_mapping[tag][InstructionType.DONTS])
        except KeyError:
            tag = PatientType[tag]
            dos.append(comm_mapping[tag][InstructionType.DOS])
            donts.append(comm_mapping[tag][InstructionType.DONTS])

    return dos, donts
