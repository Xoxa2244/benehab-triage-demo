def format_chat_history(messages: list[dict[str, str]], max_messages: int = 20) -> str:
    """
    Форматирует историю сообщений для промпта.
    Показывает только последние N сообщений для оптимизации контекста.
    
    Args:
        messages: Список сообщений в формате [{"role": "patient|nurse", "content": "...", "timestamp": "..."}]
        max_messages: Максимальное количество последних сообщений для показа (по умолчанию 10)
    
    Returns:
        Отформатированная строка истории чата
    """
    if not messages:
        return "История чата пуста."
    
    # Берем только последние max_messages сообщений
    recent_messages = messages[-max_messages:] if len(messages) > max_messages else messages
    
    formatted_lines = []
    for msg in recent_messages:
        role = msg.get("role", "unknown")
        content = msg.get("content", "")
        
        # Переводим роли на русский для промпта
        role_ru = "Пациент" if role == "patient" else "Медсестра"
        formatted_lines.append(f"{role_ru}: {content}")
    
    return "\n".join(formatted_lines)